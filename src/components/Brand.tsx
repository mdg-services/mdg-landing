import Image from "next/image";

/* Brand assets — the real MDG Services logo.
   PNGs live in /public and are generated by scripts/gen-logos.mjs
   (black variants for light surfaces, white variants for navy ones).

   They go through next/image, so the browser gets a WebP or AVIF cut at the
   size it draws, not the 41-70 kB source. The width and height given here are
   the size the site draws them at, to the pixel the 640x214 source works out
   to at 36 and 40 px high (and 384x392 for the mark), which also reserves the
   space before the file arrives. */

export function LogoFull({ className, priority = false }: { className?: string; priority?: boolean }) {
  return (
    <Image
      src="/logo-full.png"
      alt="MDG Services"
      width={107}
      height={36}
      priority={priority}
      className={className}
      draggable={false}
    />
  );
}

export function LogoFullWhite({ className }: { className?: string }) {
  return <Image src="/logo-full-white.png" alt="MDG Services" width={119} height={40} className={className} draggable={false} />;
}

export function LogoMark({
  white = false,
  className,
  alt = "MDG Services",
}: {
  white?: boolean;
  className?: string;
  alt?: string;
}) {
  return (
    <Image
      src={white ? "/logo-mark-white.png" : "/logo-mark.png"}
      alt={alt}
      width={64}
      height={64}
      className={className}
      draggable={false}
    />
  );
}
