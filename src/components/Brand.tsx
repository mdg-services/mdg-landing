import Image from "next/image";

/* Brand assets — the real MDG Services logo.
   PNGs live in /public and are generated by scripts/gen-logos.mjs
   (black variants for light surfaces, white variants for navy ones).

   They go through next/image, so the browser gets a WebP or AVIF cut at the
   size it draws, not the 41-70 kB source. The width and height given here are
   the size the site draws them at, to the pixel the 640x214 source works out
   to at 36 and 40 px high (and 384x392 for the mark), which also reserves the
   space before the file arrives. */

export function LogoFull({ className, priority = false }: { className?: string; priority?: boolean }) {
  return (
    <Image
      src="/logo-full.png"
      alt="MDG Services"
      width={107}
      height={36}
      priority={priority}
      className={className}
      draggable={false}
    />
  );
}

export function LogoFullWhite({ className }: { className?: string }) {
  return <Image src="/logo-full-white.png" alt="MDG Services" width={119} height={40} className={className} draggable={false} />;
}

export function LogoMark({
  white = false,
  className,
  alt = "MDG Services",
}: {
  white?: boolean;
  className?: string;
  alt?: string;
}) {
  return (
    <Image
      src={white ? "/logo-mark-white.png" : "/logo-mark.png"}
      alt={alt}
      width={64}
      height={64}
      className={className}
      draggable={false}
    />
  );
}

/* ── Khata Kavach's own marks (public/kk, from its brand guide) ──
   Outlined-path SVGs: no font is loaded to draw them, so they do not go
   through next/image. The width and height are the file's own aspect, so the
   space is held before it arrives. The lockup reads Hindi-first on the Hindi
   page and English-first on the English one. */

const KK_LOCKUP: Record<"en" | "hi", { w: number; h: number }> = {
  en: { w: 1071, h: 286 },
  hi: { w: 974, h: 286 },
};

export function KkLockup({
  lang,
  white = false,
  className,
  alt,
  eager = false,
}: {
  lang: "en" | "hi";
  white?: boolean;
  className?: string;
  alt: string;
  /** True only for the one on the first screen; every other one waits until it is near. */
  eager?: boolean;
}) {
  const { w, h } = KK_LOCKUP[lang];
  return (
    // eslint-disable-next-line @next/next/no-img-element
    <img
      src={`/kk/lockup-${lang}${white ? "-white" : ""}.svg`}
      alt={alt}
      width={w}
      height={h}
      className={className}
      draggable={false}
      decoding="async"
      loading={eager ? undefined : "lazy"}
    />
  );
}

export function KkMark({ white = false, small = false, className, alt = "" }: { white?: boolean; small?: boolean; className?: string; alt?: string }) {
  const src = small ? "/kk/mark-small.svg" : white ? "/kk/mark-white.svg" : "/kk/mark.svg";
  return (
    // eslint-disable-next-line @next/next/no-img-element
    <img src={src} alt={alt} width={64} height={small ? 69 : 64} className={className} draggable={false} decoding="async" loading="lazy" />
  );
}
